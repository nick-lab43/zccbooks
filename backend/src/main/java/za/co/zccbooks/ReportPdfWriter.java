package za.co.zccbooks;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.List;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;

final class ReportPdfWriter {
    private static final float MARGIN = 28f;
    private static final float FONT_SIZE = 6.5f;
    private static final float LINE_HEIGHT = 8f;
    private static final PDType1Font FONT = new PDType1Font(Standard14Fonts.FontName.HELVETICA);
    private static final PDType1Font BOLD = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);

    private ReportPdfWriter() {}

    static byte[] create(String title, String scope, String from, String to, String generatedBy,
            List<String> headers, List<String[]> rows) throws IOException {
        try (PDDocument document = new PDDocument(); ByteArrayOutputStream output = new ByteArrayOutputStream()) {
            PDRectangle pageSize = new PDRectangle(PDRectangle.A4.getHeight(), PDRectangle.A4.getWidth());
            float tableWidth = pageSize.getWidth() - 2 * MARGIN;
            float[] widths = new float[headers.size()];
            for (int i = 0; i < widths.length; i++) widths[i] = tableWidth / widths.length;
            Page page = newPage(document, pageSize, title, scope, from, to, generatedBy, rows.size());
            float y = page.y();

            y = drawRow(page.stream(), headers.toArray(String[]::new), widths, y, true);
            for (String[] row : rows) {
                float needed = rowHeight(row, widths);
                if (y - needed < MARGIN + 24) {
                    page.stream().close();
                    page = newPage(document, pageSize, title, scope, from, to, generatedBy, rows.size());
                    y = drawRow(page.stream(), headers.toArray(String[]::new), widths, page.y(), true);
                }
                y = drawRow(page.stream(), row, widths, y, false);
            }
            page.stream().close();
            document.save(output);
            return output.toByteArray();
        }
    }

    private static Page newPage(PDDocument document, PDRectangle size, String title, String scope,
            String from, String to, String generatedBy, int rowCount) throws IOException {
        PDPage page = new PDPage(size);
        document.addPage(page);
        PDPageContentStream stream = new PDPageContentStream(document, page);
        float y = size.getHeight() - MARGIN;
        text(stream, BOLD, 15, MARGIN, y, "ZION CHRISTIAN CHURCH");
        y -= 22;
        text(stream, BOLD, 11, MARGIN, y, title);
        y -= 16;
        text(stream, FONT, 7.5f, MARGIN, y, "Geographical scope: " + scope);
        y -= 11;
        text(stream, FONT, 7.5f, MARGIN, y, "Reporting period: " + from + " to " + to);
        y -= 11;
        text(stream, FONT, 7.5f, MARGIN, y, "Generated: " + java.time.OffsetDateTime.now()
            + " | Generated by: " + generatedBy);
        y -= 11;
        text(stream, BOLD, 7.5f, MARGIN, y, "CONFIDENTIAL - FOR AUTHORISED CHURCH ADMINISTRATION"
            + " | Records: " + rowCount);
        y -= 18;
        return new Page(stream, y);
    }

    private static float drawRow(PDPageContentStream stream, String[] values, float[] widths,
            float top, boolean header) throws IOException {
        float height = rowHeight(values, widths);
        float x = MARGIN;
        for (int i = 0; i < widths.length; i++) {
            stream.setLineWidth(0.35f);
            stream.addRect(x, top - height, widths[i], height);
            stream.stroke();
            List<String> lines = wrap(safe(i < values.length ? values[i] : ""), widths[i] - 6,
                header ? BOLD : FONT, FONT_SIZE);
            float baseline = top - 10;
            for (String line : lines) {
                text(stream, header ? BOLD : FONT, FONT_SIZE, x + 3, baseline, line);
                baseline -= LINE_HEIGHT;
            }
            x += widths[i];
        }
        return top - height;
    }

    private static float rowHeight(String[] values, float[] widths) throws IOException {
        int max = 1;
        for (int i = 0; i < widths.length; i++) {
            List<String> lines = wrap(safe(i < values.length ? values[i] : ""), widths[i] - 6,
                FONT, FONT_SIZE);
            max = Math.max(max, lines.size());
        }
        return Math.max(18, max * LINE_HEIGHT + 5);
    }

    private static List<String> wrap(String value, float width, PDType1Font font, float size) throws IOException {
        if (value.isBlank()) return List.of("");
        java.util.ArrayList<String> lines = new java.util.ArrayList<>();
        StringBuilder line = new StringBuilder();
        for (String word : value.split("\\s+")) {
            String candidate = line.isEmpty() ? word : line + " " + word;
            if (!line.isEmpty() && font.getStringWidth(candidate) * size / 1000f > width) {
                lines.add(line.toString());
                line.setLength(0);
                line.append(word);
            } else {
                if (!line.isEmpty()) line.append(' ');
                line.append(word);
            }
        }
        if (!line.isEmpty()) lines.add(line.toString());
        return lines;
    }

    private static void text(PDPageContentStream stream, PDType1Font font, float size,
            float x, float y, String value) throws IOException {
        stream.beginText();
        stream.setFont(font, size);
        stream.newLineAtOffset(x, y);
        stream.showText(safe(value));
        stream.endText();
    }

    private static String safe(String value) {
        if (value == null) return "";
        return value.replace('—', '-').replace('–', '-').replace('’', '\'')
            .replace('“', '"').replace('”', '"')
            .replaceAll("[^\\x20-\\x7E\\u00A0-\\u00FF]", "?");
    }

    private record Page(PDPageContentStream stream, float y) {}
}
